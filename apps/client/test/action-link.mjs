import assert from 'node:assert/strict';
import {activityFileLink,decodeSgrMouse} from '../dist/action-link.js';
import {isReadOnlyTool} from '../dist/tool-presentation.js';
const base={id:'test',time:0,tool:'fs_read',cwd:process.cwd(),request_json:JSON.stringify({path:'src/test.ts',lineOffset:310})};
const link=activityFileLink(base);
assert.equal(link?.label,'test.ts');
assert.equal(link?.line,311);
assert.ok(link?.path.endsWith('src'+(process.platform==='win32'?'\\':'/')+'test.ts'));
assert.equal(activityFileLink({...base,tool:'exec_foreground'}),null);
assert.equal(activityFileLink({...base,tool:'fs_write',request_json:'{"path":"test.txt"}'})?.line,undefined);
assert.deepEqual(decodeSgrMouse('\x1b[<64;2;9M').map(x=>x.kind),['wheel']);
assert.deepEqual(decodeSgrMouse('\x1b[<35;15;7M').map(x=>x.kind),['move']);
assert.equal(decodeSgrMouse('\x1b[<16;15;7M')[0]?.ctrl,true);
assert.equal(decodeSgrMouse('\x1b[<0;15;7m').length,0);
assert.equal(isReadOnlyTool('fs_read'),true);
assert.equal(isReadOnlyTool('fs_write'),false);
assert.equal(isReadOnlyTool('exec_foreground'),false);
assert.equal(isReadOnlyTool('http_request',JSON.stringify({method:'GET'})),true);
assert.equal(isReadOnlyTool('http_request',JSON.stringify({method:'POST'})),false);
assert.equal(isReadOnlyTool('fs_archive',JSON.stringify({action:'list'})),true);
assert.equal(isReadOnlyTool('fs_archive',JSON.stringify({action:'extract'})),false);
console.log('PASS file links, Ctrl+mouse decoding, and read-only TOOL emphasis');
