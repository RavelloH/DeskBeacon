import assert from 'node:assert/strict';
import {EventEmitter} from 'node:events';
import {closeSync,openSync,readFileSync,mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {installTuiTerminalGuard,TUI_ENTER_TERMINAL,TUI_RESTORE_TERMINAL} from '../dist/tui-terminal-guard.js';

const root=mkdtempSync(join(tmpdir(),'deskbeacon-terminal-guard-'));
let fd;
try{
 fd=openSync(join(root,'emergency.txt'),'w+');
 const host=new EventEmitter();
 const fatalEvents=[];
 const recordCritical=(event,details)=>fatalEvents.push({event,details});
 let exits=0,raw=true,normal='';
 host.exit=()=>{exits++};
 const out={isTTY:true,fd,write:(text,done)=>{normal+=text;done?.();return true}};
 const stdin={setRawMode:val=>{raw=val;}};
 const guard=installTuiTerminalGuard(out,stdin,host,recordCritical);
 guard.enter();assert.equal(normal,TUI_ENTER_TERMINAL);
 host.emit('exit');
 assert.equal(readFileSync(join(root,'emergency.txt'),'utf8'),TUI_RESTORE_TERMINAL);
 assert.equal(raw,false);
 guard.dispose();
 const before=readFileSync(join(root,'emergency.txt'),'utf8');
 host.emit('exit');
 assert.equal(readFileSync(join(root,'emergency.txt'),'utf8'),before,'guard must unregister event listeners');
 raw=true;
 const another=installTuiTerminalGuard(out,stdin,host,recordCritical);
 another.enter();
 await another.restore();
 assert.ok(normal.endsWith(TUI_RESTORE_TERMINAL));
 assert.equal(raw,false);
 another.dispose();
 const term=installTuiTerminalGuard(out,stdin,host,recordCritical);
 term.enter();host.emit('SIGTERM');
 assert.equal(exits,1,'SIGTERM handler must allow process to terminate');
 assert.equal(host.exitCode,143);
 term.dispose();
 const ctrl=installTuiTerminalGuard(out,stdin,host,recordCritical);
 ctrl.enter();host.emit('SIGINT');
 assert.equal(exits,2);
 assert.equal(host.exitCode,130,'SIGINT must use conventional exit status 130');
 assert.deepEqual(fatalEvents.map(e=>e.details.signal),['SIGTERM','SIGINT']);
 const crash=installTuiTerminalGuard(out,stdin,host,recordCritical);
 crash.enter();host.emit('uncaughtExceptionMonitor',new Error('test fatal'),'uncaughtException');
 assert.equal(fatalEvents.at(-1).event,'session.uncaught');
 assert.match(fatalEvents.at(-1).details.error.message,/test fatal/);
 crash.dispose();
 ctrl.dispose();
 console.log('PASS terminal recovery on process exit, graceful close, SIGTERM, and listener removal');
}finally{if(fd!==undefined)closeSync(fd);rmSync(root,{recursive:true,force:true});}
